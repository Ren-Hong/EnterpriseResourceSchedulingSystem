/*
   ERSS scheduling schema upgrade.
   Run against the ERSS database after InitializeErss.sql.
   Safe to re-run; existing resource, fee, slot and booking rows are retained.
*/
USE [ERSS];
GO
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;
SET NUMERIC_ROUNDABORT OFF;
BEGIN TRANSACTION;

/* Version resource configuration. Current resource values become version 1. */
IF OBJECT_ID(N'dbo.ERSSRESCFGTBL', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ERSSRESCFGTBL
    (
        UIDRESCFGID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_UIDRESCFGID DEFAULT NEWSEQUENTIALID(),
        UIDRESID UNIQUEIDENTIFIER NOT NULL,
        NUMRESCFGNO INT NOT NULL,
        NVCHRESNAME NVARCHAR(100) NOT NULL,
        NVCHRESDESC NVARCHAR(500) NULL,
        INTMAXUSER INT NOT NULL,
        DTMEFFECTSTART DATE NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_DTMEFFECTSTART DEFAULT ('19000101'),
        DTMEFFECTEND DATE NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_DTMEFFECTEND DEFAULT ('99991231'),
        NVCHREASON NVARCHAR(500) NULL,
        VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
        DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
        VCHUPDATEBY NVARCHAR(50) NULL,
        DTMUPDATEDAT DATETIME2(0) NULL,
        CONSTRAINT PK_ERSSRESCFGTBL PRIMARY KEY (UIDRESCFGID),
        CONSTRAINT UQ_ERSSRESCFGTBL_RES_VER UNIQUE (UIDRESID, NUMRESCFGNO),
        CONSTRAINT FK_ERSSRESCFGTBL_ERSSRESTBL FOREIGN KEY (UIDRESID) REFERENCES dbo.ERSSRESTBL (UIDRESID),
        CONSTRAINT CK_ERSSRESCFGTBL_MAXUSER CHECK (INTMAXUSER > 0),
        CONSTRAINT CK_ERSSRESCFGTBL_EFFECTIVE CHECK (DTMEFFECTEND >= DTMEFFECTSTART)
    );
END;

INSERT INTO dbo.ERSSRESCFGTBL (UIDRESID, NUMRESCFGNO, NVCHRESNAME, NVCHRESDESC, INTMAXUSER, DTMEFFECTSTART, VCHCREATEBY, DTMCREATEDAT)
SELECT r.UIDRESID, 1, r.NVCHRESNAME, r.NVCHRESDESC, r.INTMAXUSER, '19000101', r.VCHCREATEBY, r.DTMCREATEDAT
FROM dbo.ERSSRESTBL AS r
WHERE NOT EXISTS (SELECT 1 FROM dbo.ERSSRESCFGTBL AS c WHERE c.UIDRESID = r.UIDRESID);

/* Fee entries belong to a resource configuration. */
IF COL_LENGTH(N'dbo.ERSSRESFEETBL', N'UIDRESCFGID') IS NULL
    ALTER TABLE dbo.ERSSRESFEETBL ADD UIDRESCFGID UNIQUEIDENTIFIER NULL;

IF COL_LENGTH(N'dbo.ERSSRESFEETBL', N'UIDRESID') IS NOT NULL
BEGIN
    EXEC sys.sp_executesql N'
        UPDATE f
        SET UIDRESCFGID = c.UIDRESCFGID
        FROM dbo.ERSSRESFEETBL AS f
        JOIN dbo.ERSSRESCFGTBL AS c ON c.UIDRESID = f.UIDRESID AND c.NUMRESCFGNO = 1
        WHERE f.UIDRESCFGID IS NULL;';
END;

IF COL_LENGTH(N'dbo.ERSSRESFEETBL', N'DTMEFFECTSTART') IS NOT NULL
BEGIN
    EXEC sys.sp_executesql N'
IF EXISTS
(
    SELECT 1 FROM sys.key_constraints
    WHERE parent_object_id = OBJECT_ID(N''dbo.ERSSRESFEETBL'')
      AND name = N''UQ_ERSSRESFEETBL_RATESTART''
)
    ALTER TABLE dbo.ERSSRESFEETBL DROP CONSTRAINT UQ_ERSSRESFEETBL_RATESTART;
IF EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N''dbo.ERSSRESFEETBL'') AND name = N''UQ_ERSSRESFEETBL_CFG_RATESTART'')
    DROP INDEX UQ_ERSSRESFEETBL_CFG_RATESTART ON dbo.ERSSRESFEETBL;
IF EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N''dbo.ERSSRESFEETBL'') AND name = N''IX_ERSSRESFEETBL_CFG_IDN'')
    DROP INDEX IX_ERSSRESFEETBL_CFG_IDN ON dbo.ERSSRESFEETBL;
IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(N''dbo.ERSSRESFEETBL'') AND name = N''CK_ERSSRESFEETBL_EFFECTIVE'')
    ALTER TABLE dbo.ERSSRESFEETBL DROP CONSTRAINT CK_ERSSRESFEETBL_EFFECTIVE;

/* Previous NULL end dates meant open-ended validity. Convert those legacy rows
   to an explicit far-future date before enforcing required end dates. */
UPDATE dbo.ERSSRESFEETBL SET DTMEFFECTEND = CONVERT(DATE, ''99991231'', 112) WHERE DTMEFFECTEND IS NULL;
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID(N''dbo.ERSSRESFEETBL'') AND name = N''UIDRESCFGID'' AND is_nullable = 1)
    ALTER TABLE dbo.ERSSRESFEETBL ALTER COLUMN UIDRESCFGID UNIQUEIDENTIFIER NOT NULL;
ALTER TABLE dbo.ERSSRESFEETBL ALTER COLUMN DTMEFFECTSTART DATE NOT NULL;
ALTER TABLE dbo.ERSSRESFEETBL ALTER COLUMN DTMEFFECTEND DATE NOT NULL;

IF EXISTS
(
    SELECT 1 FROM dbo.ERSSRESFEETBL AS a
    INNER JOIN dbo.ERSSRESFEETBL AS b
        ON b.UIDRESCFGID = a.UIDRESCFGID
       AND b.UIDIDNTYPE = a.UIDIDNTYPE
       AND b.UIDRESFEEID > a.UIDRESFEEID
       AND a.DTMEFFECTSTART <= b.DTMEFFECTEND
       AND b.DTMEFFECTSTART <= a.DTMEFFECTEND
)
    THROW 50001, ''Fee periods overlap after conversion to calendar dates. Resolve the conflicting fee rows, then rerun this migration.'', 1;

ALTER TABLE dbo.ERSSRESFEETBL ADD CONSTRAINT CK_ERSSRESFEETBL_EFFECTIVE CHECK (DTMEFFECTEND >= DTMEFFECTSTART);
CREATE UNIQUE INDEX UQ_ERSSRESFEETBL_CFG_RATESTART ON dbo.ERSSRESFEETBL (UIDRESCFGID, UIDIDNTYPE, DTMEFFECTSTART);';

END;

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_ERSSRESFEETBL_ERSSRESCFGTBL')
    ALTER TABLE dbo.ERSSRESFEETBL ADD CONSTRAINT FK_ERSSRESFEETBL_ERSSRESCFGTBL
        FOREIGN KEY (UIDRESCFGID) REFERENCES dbo.ERSSRESCFGTBL (UIDRESCFGID);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.ERSSRESFEETBL') AND name = N'IX_ERSSRESFEETBL_CFG_IDN')
    CREATE INDEX IX_ERSSRESFEETBL_CFG_IDN ON dbo.ERSSRESFEETBL (UIDRESCFGID, UIDIDNTYPE);

/* The configuration version already determines the resource; avoid storing a
   second resource FK that could disagree with UIDRESCFGID. */
IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_ERSSRESFEETBL_ERSSRESTBL')
    ALTER TABLE dbo.ERSSRESFEETBL DROP CONSTRAINT FK_ERSSRESFEETBL_ERSSRESTBL;
IF COL_LENGTH(N'dbo.ERSSRESFEETBL', N'UIDRESID') IS NOT NULL
    ALTER TABLE dbo.ERSSRESFEETBL DROP COLUMN UIDRESID;

/* Rename the old available-slot table and make its version dependency explicit. */
IF OBJECT_ID(N'dbo.ERSSSCHTBL', N'U') IS NOT NULL AND OBJECT_ID(N'dbo.ERSSSLOTTBL', N'U') IS NULL
    EXEC sys.sp_rename N'dbo.ERSSSCHTBL', N'ERSSSLOTTBL';

IF COL_LENGTH(N'dbo.ERSSSLOTTBL', N'UIDSCHID') IS NOT NULL
    EXEC sys.sp_rename N'dbo.ERSSSLOTTBL.UIDSCHID', N'UIDSLOTID', N'COLUMN';

IF COL_LENGTH(N'dbo.ERSSSLOTTBL', N'UIDRESCFGID') IS NULL
    ALTER TABLE dbo.ERSSSLOTTBL ADD UIDRESCFGID UNIQUEIDENTIFIER NULL;

EXEC sys.sp_executesql N'
UPDATE s
SET UIDRESCFGID = c.UIDRESCFGID
FROM dbo.ERSSSLOTTBL AS s
JOIN dbo.ERSSRESCFGTBL AS c ON c.UIDRESID = s.UIDRESID AND c.NUMRESCFGNO = 1
WHERE s.UIDRESCFGID IS NULL;';

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_ERSSSLOTTBL_ERSSRESCFGTBL')
    ALTER TABLE dbo.ERSSSLOTTBL ADD CONSTRAINT FK_ERSSSLOTTBL_ERSSRESCFGTBL
        FOREIGN KEY (UIDRESCFGID) REFERENCES dbo.ERSSRESCFGTBL (UIDRESCFGID);

/* Turn the old slot-person detail table into the actual booking table. */
IF OBJECT_ID(N'dbo.ERSSSCHUSERTBL', N'U') IS NOT NULL AND OBJECT_ID(N'dbo.ERSSSCHTBL', N'U') IS NULL
    EXEC sys.sp_rename N'dbo.ERSSSCHUSERTBL', N'ERSSSCHTBL';

/* First rename the existing slot reference out of the way, then use UIDSCHID
   for the new actual-booking primary key. */
IF COL_LENGTH(N'dbo.ERSSSCHTBL', N'UIDSCHID') IS NOT NULL AND COL_LENGTH(N'dbo.ERSSSCHTBL', N'UIDSLOTID') IS NULL
    EXEC sys.sp_rename N'dbo.ERSSSCHTBL.UIDSCHID', N'UIDSLOTID', N'COLUMN';
IF COL_LENGTH(N'dbo.ERSSSCHTBL', N'UIDSCHUSERID') IS NOT NULL
    EXEC sys.sp_rename N'dbo.ERSSSCHTBL.UIDSCHUSERID', N'UIDSCHID', N'COLUMN';

IF COL_LENGTH(N'dbo.ERSSSCHTBL', N'VCHCANCELBY') IS NULL
    ALTER TABLE dbo.ERSSSCHTBL ADD VCHCANCELBY NVARCHAR(50) NULL;
IF COL_LENGTH(N'dbo.ERSSSCHTBL', N'VCHUPDATEBY') IS NULL
    ALTER TABLE dbo.ERSSSCHTBL ADD VCHUPDATEBY NVARCHAR(50) NULL;
IF COL_LENGTH(N'dbo.ERSSSCHTBL', N'DTMUPDATEDAT') IS NULL
    ALTER TABLE dbo.ERSSSCHTBL ADD DTMUPDATEDAT DATETIME2(0) NULL;

/* Keep recorded booking amounts in NUMFEE when removing the old slot fee snapshots. */
IF EXISTS (
    SELECT 1 FROM sys.foreign_keys
    WHERE parent_object_id = OBJECT_ID(N'dbo.ERSSSCHTBL') AND name = N'FK_ERSSSCHTBL_ERSSSLOTFEE'
)
    ALTER TABLE dbo.ERSSSCHTBL DROP CONSTRAINT FK_ERSSSCHTBL_ERSSSLOTFEE;

IF COL_LENGTH(N'dbo.ERSSSCHTBL', N'UIDSLOTFEEID') IS NOT NULL
    ALTER TABLE dbo.ERSSSCHTBL DROP COLUMN UIDSLOTFEEID;

IF OBJECT_ID(N'dbo.ERSSSLOTFEETBL', N'U') IS NOT NULL
    DROP TABLE dbo.ERSSSLOTFEETBL;

/* Rename the old FK object name if still present; the FK remains linked to the
   renamed slot table/column by SQL Server object identity. */
IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_ERSSSCHUSERTBL_ERSSSCHTBL')
    EXEC sys.sp_rename N'dbo.FK_ERSSSCHUSERTBL_ERSSSCHTBL', N'FK_ERSSSCHTBL_ERSSSLOTTBL', N'OBJECT';

/* Retain cancelled slots while allowing a replacement at the same time. */
IF EXISTS (
    SELECT 1 FROM sys.key_constraints
    WHERE parent_object_id = OBJECT_ID(N'dbo.ERSSSLOTTBL') AND name = N'UQ_ERSSSCHTBL_RES_TIME'
)
    ALTER TABLE dbo.ERSSSLOTTBL DROP CONSTRAINT UQ_ERSSSCHTBL_RES_TIME;

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID(N'dbo.ERSSSLOTTBL') AND name = N'UQ_ERSSSLOTTBL_ACTIVE_RES_TIME'
)
    CREATE UNIQUE INDEX UQ_ERSSSLOTTBL_ACTIVE_RES_TIME
    ON dbo.ERSSSLOTTBL (UIDRESID, DTMSTARTAT, DTMENDAT)
    WHERE NVCHSTATUS <> N'CANCELLED';
/* Retain cancelled bookings while allowing the person to book the same slot again. */
IF EXISTS (
    SELECT 1 FROM sys.key_constraints
    WHERE parent_object_id = OBJECT_ID(N'dbo.ERSSSCHTBL') AND name = N'UQ_ERSSSCHUSERTBL_SCH_USER'
)
    ALTER TABLE dbo.ERSSSCHTBL DROP CONSTRAINT UQ_ERSSSCHUSERTBL_SCH_USER;

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID(N'dbo.ERSSSCHTBL') AND name = N'UQ_ERSSSCHTBL_ACTIVE_SLOT_USER'
)
    CREATE UNIQUE INDEX UQ_ERSSSCHTBL_ACTIVE_SLOT_USER
    ON dbo.ERSSSCHTBL (UIDSLOTID, UIDUSERID)
    WHERE NVCHSTATUS = N'BOOKED';

IF DATABASE_PRINCIPAL_ID(N'erss_app') IS NOT NULL
BEGIN
    GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSRESCFGTBL TO [erss_app];
    GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSSLOTTBL TO [erss_app];
    GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSSCHTBL TO [erss_app];
END;

COMMIT TRANSACTION;
GO

