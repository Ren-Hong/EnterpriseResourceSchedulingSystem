USE [master];
GO

IF DB_ID(N'ERSS') IS NULL
    CREATE DATABASE [ERSS];
GO

USE [ERSS];
GO

IF OBJECT_ID(N'dbo.ERSSUSERTBL', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ERSSUSERTBL
    (
        UIDUSERID UNIQUEIDENTIFIER NOT NULL
            CONSTRAINT DF_ERSSUSERTBL_UIDUSERID DEFAULT NEWSEQUENTIALID(),
        NVCHUSERNAME NVARCHAR(50) COLLATE Latin1_General_100_CI_AS_SC NOT NULL,
        VCHPASSWORDHASH VARCHAR(255) COLLATE Latin1_General_100_BIN2 NOT NULL,
        NVCHDISPLAYNAME NVARCHAR(100) NULL,
        NVCHLEVEL NVARCHAR(10) COLLATE Latin1_General_100_BIN2 NOT NULL
            CONSTRAINT DF_ERSSUSERTBL_NVCHLEVEL DEFAULT (N'一般使用者'),
        BITISACTIVE BIT NOT NULL
            CONSTRAINT DF_ERSSUSERTBL_BITISACTIVE DEFAULT (1),
        DTMCREATEDAT DATETIME2(0) NOT NULL
            CONSTRAINT DF_ERSSUSERTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
        DTMUPDATEDAT DATETIME2(0) NULL,
        DTMLASTLOGINAT DATETIME2(0) NULL,
        CONSTRAINT PK_ERSSUSERTBL PRIMARY KEY (UIDUSERID),
        CONSTRAINT UQ_ERSSUSERTBL_NVCHUSERNAME UNIQUE (NVCHUSERNAME),
        CONSTRAINT CK_ERSSUSERTBL_NVCHUSERNAME CHECK
        (
            LEN(TRIM(NVCHUSERNAME)) > 0
            AND DATALENGTH(NVCHUSERNAME) = DATALENGTH(TRIM(NVCHUSERNAME))
        ),
        CONSTRAINT CK_ERSSUSERTBL_NVCHLEVEL CHECK
        (
            NVCHLEVEL IN (N'管理員', N'一般使用者')
            AND DATALENGTH(NVCHLEVEL) = DATALENGTH(RTRIM(NVCHLEVEL))
        )
    );
END
ELSE IF COL_LENGTH(N'dbo.ERSSUSERTBL', N'UserId') IS NOT NULL
BEGIN
    SET XACT_ABORT ON;
    BEGIN TRANSACTION;

    ALTER TABLE dbo.ERSSUSERTBL DROP CONSTRAINT CK_ERSSUSERTBL_Username;

    EXEC sys.sp_rename N'dbo.ERSSUSERTBL.UserId', N'UIDUSERID', N'COLUMN';
    EXEC sys.sp_rename N'dbo.ERSSUSERTBL.Username', N'NVCHUSERNAME', N'COLUMN';
    EXEC sys.sp_rename N'dbo.ERSSUSERTBL.PasswordHash', N'VCHPASSWORDHASH', N'COLUMN';
    EXEC sys.sp_rename N'dbo.ERSSUSERTBL.DisplayName', N'NVCHDISPLAYNAME', N'COLUMN';
    EXEC sys.sp_rename N'dbo.ERSSUSERTBL.IsActive', N'BITISACTIVE', N'COLUMN';

    IF COL_LENGTH(N'dbo.ERSSUSERTBL', N'CreatedAtUtc') IS NOT NULL
    BEGIN
        EXEC sys.sp_rename N'dbo.ERSSUSERTBL.CreatedAtUtc', N'DTMCREATEDAT', N'COLUMN';
        EXEC sys.sp_rename N'dbo.ERSSUSERTBL.UpdatedAtUtc', N'DTMUPDATEDAT', N'COLUMN';
        EXEC sys.sp_rename N'dbo.ERSSUSERTBL.LastLoginAtUtc', N'DTMLASTLOGINAT', N'COLUMN';
        EXEC sys.sp_rename N'dbo.DF_ERSSUSERTBL_CreatedAtUtc', N'DF_ERSSUSERTBL_DTMCREATEDAT', N'OBJECT';
    END
    ELSE
    BEGIN
        EXEC sys.sp_rename N'dbo.ERSSUSERTBL.CreatedAt', N'DTMCREATEDAT', N'COLUMN';
        EXEC sys.sp_rename N'dbo.ERSSUSERTBL.UpdatedAt', N'DTMUPDATEDAT', N'COLUMN';
        EXEC sys.sp_rename N'dbo.ERSSUSERTBL.LastLoginAt', N'DTMLASTLOGINAT', N'COLUMN';
        EXEC sys.sp_rename N'dbo.DF_ERSSUSERTBL_CreatedAt', N'DF_ERSSUSERTBL_DTMCREATEDAT', N'OBJECT';
    END;

    EXEC sys.sp_rename N'dbo.DF_ERSSUSERTBL_UserId', N'DF_ERSSUSERTBL_UIDUSERID', N'OBJECT';
    EXEC sys.sp_rename N'dbo.DF_ERSSUSERTBL_IsActive', N'DF_ERSSUSERTBL_BITISACTIVE', N'OBJECT';
    EXEC sys.sp_rename N'dbo.UQ_ERSSUSERTBL_Username', N'UQ_ERSSUSERTBL_NVCHUSERNAME', N'OBJECT';

    EXEC sys.sp_executesql N'
        ALTER TABLE dbo.ERSSUSERTBL WITH CHECK ADD CONSTRAINT CK_ERSSUSERTBL_NVCHUSERNAME CHECK
        (
            LEN(TRIM(NVCHUSERNAME)) > 0
            AND DATALENGTH(NVCHUSERNAME) = DATALENGTH(TRIM(NVCHUSERNAME))
        );';

    ALTER TABLE dbo.ERSSUSERTBL ADD NVCHLEVEL NVARCHAR(10) COLLATE Latin1_General_100_BIN2 NOT NULL
        CONSTRAINT DF_ERSSUSERTBL_NVCHLEVEL DEFAULT (N'一般使用者');

    EXEC sys.sp_executesql N'
        ALTER TABLE dbo.ERSSUSERTBL WITH CHECK ADD CONSTRAINT CK_ERSSUSERTBL_NVCHLEVEL CHECK
        (
            NVCHLEVEL IN (N''管理員'', N''一般使用者'')
            AND DATALENGTH(NVCHLEVEL) = DATALENGTH(RTRIM(NVCHLEVEL))
        );';

    COMMIT TRANSACTION;
END;
GO

IF DATABASE_PRINCIPAL_ID(N'erss_app') IS NOT NULL
    GRANT SELECT ON OBJECT::dbo.ERSSUSERTBL (NVCHLEVEL) TO [erss_app];
GO
