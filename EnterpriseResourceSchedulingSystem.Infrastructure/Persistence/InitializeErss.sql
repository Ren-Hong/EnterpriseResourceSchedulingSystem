IF COL_LENGTH(N'dbo.ERSSACCTBL', N'BITISACTIVE') IS NOT NULL
BEGIN
    IF DATABASE_PRINCIPAL_ID(N'erss_app') IS NOT NULL
        REVOKE SELECT ON OBJECT::dbo.ERSSACCTBL (BITISACTIVE) FROM [erss_app];
    DECLARE @acctDefault sysname;
    SELECT @acctDefault = dc.name
    FROM sys.default_constraints dc
    JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id
    WHERE dc.parent_object_id = OBJECT_ID(N'dbo.ERSSACCTBL') AND c.name = N'BITISACTIVE';
    IF @acctDefault IS NOT NULL
    BEGIN
        DECLARE @dropAcctDefault NVARCHAR(400) = N'ALTER TABLE dbo.ERSSACCTBL DROP CONSTRAINT ' + QUOTENAME(@acctDefault);
        EXEC sys.sp_executesql @dropAcctDefault;
    END;
    ALTER TABLE dbo.ERSSACCTBL DROP COLUMN BITISACTIVE;
END;
GO

