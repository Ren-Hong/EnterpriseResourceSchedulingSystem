/* ERSS schema for a new, empty Azure SQL Database or SQL Server database.
   Connect directly to the target database before running the entire script.
   Application sign-in accounts and database users are provisioned separately. */
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;
SET NUMERIC_ROUNDABORT OFF;

-- 僅供初始化空白資料庫。若 dbo 已有資料表，先停止以避免部分初始化。
IF EXISTS (SELECT 1 FROM sys.tables WHERE schema_id = SCHEMA_ID(N'dbo'))
    THROW 50000, 'Connect to an empty ERSS database before initializing the schema.', 1;

-- 資料表、索引和權限一起建立，避免中途失敗留下不完整的結構。
BEGIN TRANSACTION;

-- 網站登入帳號。密碼以雜湊值保存，與排程中的人員名單分開管理。
CREATE TABLE dbo.ERSSACCTBL
(
    UIDACCTID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSACCTBL_UIDACCTID DEFAULT NEWSEQUENTIALID(),
    NVCHUSERNAME NVARCHAR(50) COLLATE Latin1_General_100_CI_AS_SC NOT NULL,
    NVCHDISPLAYNAME NVARCHAR(100) NULL,
    VCHPASSWORDHASH VARCHAR(255) COLLATE Latin1_General_100_BIN2 NOT NULL,
    NVCHLEVEL NVARCHAR(10) COLLATE Latin1_General_100_BIN2 NOT NULL
        CONSTRAINT DF_ERSSACCTBL_NVCHLEVEL DEFAULT (N'一般使用者'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSACCTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    DTMUPDATEDAT DATETIME2(0) NULL,
    DTMLASTLOGINAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSACCTBL PRIMARY KEY (UIDACCTID),
    CONSTRAINT UQ_ERSSACCTBL_NVCHUSERNAME UNIQUE (NVCHUSERNAME),
    CONSTRAINT CK_ERSSACCTBL_NVCHUSERNAME CHECK
        (LEN(TRIM(NVCHUSERNAME)) > 0 AND DATALENGTH(NVCHUSERNAME) = DATALENGTH(TRIM(NVCHUSERNAME))),
    CONSTRAINT CK_ERSSACCTBL_NVCHLEVEL CHECK
        (NVCHLEVEL IN (N'管理員', N'一般使用者') AND DATALENGTH(NVCHLEVEL) = DATALENGTH(RTRIM(NVCHLEVEL)))
);

-- 身分別主檔，供人員資料與各版本的身分費率引用。
CREATE TABLE dbo.ERSSIDNTBL
(
    UIDIDNTYPE UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSIDNTBL_UIDIDNTYPE DEFAULT NEWSEQUENTIALID(),
    NVCHIDENTITYNAME NVARCHAR(50) NOT NULL,
    NVCHDESCRIPTION NVARCHAR(200) NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSIDNTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSIDNTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSIDNTBL PRIMARY KEY (UIDIDNTYPE),
    CONSTRAINT UQ_ERSSIDNTBL_NVCHIDENTITYNAME UNIQUE (NVCHIDENTITYNAME),
    CONSTRAINT CK_ERSSIDNTBL_NVCHIDENTITYNAME CHECK
        (LEN(TRIM(NVCHIDENTITYNAME)) > 0 AND DATALENGTH(NVCHIDENTITYNAME) = DATALENGTH(TRIM(NVCHIDENTITYNAME)))
);

-- 可參與排程的人員名單。尚未指定身分別時，UIDIDNTYPE 可為 NULL。
CREATE TABLE dbo.ERSSUSERTBL
(
    UIDUSERID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSUSERTBL_UIDUSERID DEFAULT NEWSEQUENTIALID(),
    UIDIDNTYPE UNIQUEIDENTIFIER NULL,
    NVCHDISPLAYNAME NVARCHAR(100) NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSUSERTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSUSERTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSUSERTBL PRIMARY KEY (UIDUSERID),
    CONSTRAINT FK_ERSSUSERTBL_ERSSIDNTBL FOREIGN KEY (UIDIDNTYPE) REFERENCES dbo.ERSSIDNTBL (UIDIDNTYPE)
);

-- 設備／資源主檔。設備名稱以此表為準，設定版本透過 UIDRESID 取得名稱。
CREATE TABLE dbo.ERSSRESTBL
(
    UIDRESID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSRESTBL_UIDRESID DEFAULT NEWSEQUENTIALID(),
    NVCHRESNAME NVARCHAR(100) NOT NULL,
    NVCHRESDESC NVARCHAR(500) NULL,
    INTMAXUSER INT NOT NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSRESTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSRESTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSRESTBL PRIMARY KEY (UIDRESID),
    CONSTRAINT UQ_ERSSRESTBL_NVCHRESNAME UNIQUE (NVCHRESNAME),
    CONSTRAINT CK_ERSSRESTBL_INTMAXUSER CHECK (INTMAXUSER > 0),
    CONSTRAINT CK_ERSSRESTBL_NVCHRESNAME CHECK
        (LEN(TRIM(NVCHRESNAME)) > 0 AND DATALENGTH(NVCHRESNAME) = DATALENGTH(TRIM(NVCHRESNAME)))
);

-- 設備設定版本。每個資源的版號唯一，生效起日與迄日均包含當天。
CREATE TABLE dbo.ERSSRESCFGTBL
(
    UIDRESCFGID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_UIDRESCFGID DEFAULT NEWSEQUENTIALID(),
    UIDRESID UNIQUEIDENTIFIER NOT NULL,
    NUMRESCFGNO INT NOT NULL,
    NVCHRESDESC NVARCHAR(500) NULL,
    INTMAXUSER INT NOT NULL,
    DTMEFFECTSTART DATE NOT NULL,
    DTMEFFECTEND DATE NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_DTMEFFECTEND DEFAULT ('99991231'),
    NVCHREASON NVARCHAR(500) NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSRESCFGTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSRESCFGTBL PRIMARY KEY (UIDRESCFGID),
    CONSTRAINT UQ_ERSSRESCFGTBL_RES_VER UNIQUE (UIDRESID, NUMRESCFGNO),
    CONSTRAINT FK_ERSSRESCFGTBL_ERSSRESTBL FOREIGN KEY (UIDRESID) REFERENCES dbo.ERSSRESTBL (UIDRESID),
    CONSTRAINT CK_ERSSRESCFGTBL_MAXUSER CHECK (INTMAXUSER > 0),
    CONSTRAINT CK_ERSSRESCFGTBL_EFFECTIVE CHECK (DTMEFFECTEND >= DTMEFFECTSTART)
);

-- 依設定版本及身分別保存目前費率，供建立預約時取價。
CREATE TABLE dbo.ERSSRESFEETBL
(
    UIDRESFEEID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSRESFEETBL_UIDRESFEEID DEFAULT NEWSEQUENTIALID(),
    UIDRESCFGID UNIQUEIDENTIFIER NOT NULL,
    UIDIDNTYPE UNIQUEIDENTIFIER NOT NULL,
    NUMFEE DECIMAL(12,2) NOT NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSRESFEETBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSRESFEETBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSRESFEETBL PRIMARY KEY (UIDRESFEEID),
    CONSTRAINT FK_ERSSRESFEETBL_ERSSRESCFGTBL FOREIGN KEY (UIDRESCFGID) REFERENCES dbo.ERSSRESCFGTBL (UIDRESCFGID),
    CONSTRAINT FK_ERSSRESFEETBL_ERSSIDNTBL FOREIGN KEY (UIDIDNTYPE) REFERENCES dbo.ERSSIDNTBL (UIDIDNTYPE),
    CONSTRAINT CK_ERSSRESFEETBL_NUMFEE CHECK (NUMFEE >= 0)
);

-- 人員可使用哪些設備及其授權期間。授權迄日為 NULL 表示沒有截止時間。
CREATE TABLE dbo.ERSSUSERRESTBL
(
    UIDUSERID UNIQUEIDENTIFIER NOT NULL,
    UIDRESID UNIQUEIDENTIFIER NOT NULL,
    DTMEFFECTSTART DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSUSERRESTBL_DTMEFFECTSTART DEFAULT SYSUTCDATETIME(),
    DTMEFFECTEND DATETIME2(0) NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSUSERRESTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSUSERRESTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSUSERRESTBL PRIMARY KEY (UIDUSERID, UIDRESID),
    CONSTRAINT FK_ERSSUSERRESTBL_ERSSUSERTBL FOREIGN KEY (UIDUSERID) REFERENCES dbo.ERSSUSERTBL (UIDUSERID),
    CONSTRAINT FK_ERSSUSERRESTBL_ERSSRESTBL FOREIGN KEY (UIDRESID) REFERENCES dbo.ERSSRESTBL (UIDRESID),
    CONSTRAINT CK_ERSSUSERRESTBL_EFFECTIVE CHECK (DTMEFFECTEND IS NULL OR DTMEFFECTEND > DTMEFFECTSTART)
);

-- 設備的可預約時段，保存選用的設定版本、UTC 起訖、名額和狀態。
CREATE TABLE dbo.ERSSSLOTTBL
(
    UIDSLOTID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSSLOTTBL_UIDSLOTID DEFAULT NEWSEQUENTIALID(),
    UIDRESID UNIQUEIDENTIFIER NOT NULL,
    UIDRESCFGID UNIQUEIDENTIFIER NULL,
    DTMSTARTAT DATETIME2(0) NOT NULL,
    DTMENDAT DATETIME2(0) NOT NULL,
    INTCAPACITY INT NOT NULL,
    NVCHSTATUS NVARCHAR(12) NOT NULL CONSTRAINT DF_ERSSSLOTTBL_NVCHSTATUS DEFAULT (N'OPEN'),
    NVCHNOTE NVARCHAR(500) NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSSLOTTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSSLOTTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    CONSTRAINT PK_ERSSSLOTTBL PRIMARY KEY (UIDSLOTID),
    CONSTRAINT FK_ERSSSLOTTBL_ERSSRESTBL FOREIGN KEY (UIDRESID) REFERENCES dbo.ERSSRESTBL (UIDRESID),
    CONSTRAINT FK_ERSSSLOTTBL_ERSSRESCFGTBL FOREIGN KEY (UIDRESCFGID) REFERENCES dbo.ERSSRESCFGTBL (UIDRESCFGID),
    CONSTRAINT CK_ERSSSLOTTBL_TIME CHECK (DTMENDAT > DTMSTARTAT),
    CONSTRAINT CK_ERSSSLOTTBL_CAPACITY CHECK (INTCAPACITY > 0),
    CONSTRAINT CK_ERSSSLOTTBL_STATUS CHECK (NVCHSTATUS IN (N'OPEN', N'CLOSED', N'CANCELLED', N'COMPLETED'))
);

-- 實際預約。每筆預約保存當時的身分別與金額，並記錄建立、取消及最後更新資訊。
CREATE TABLE dbo.ERSSSCHTBL
(
    UIDSCHID UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ERSSSCHTBL_UIDSCHID DEFAULT NEWSEQUENTIALID(),
    UIDSLOTID UNIQUEIDENTIFIER NOT NULL,
    UIDUSERID UNIQUEIDENTIFIER NOT NULL,
    UIDIDNTYPE UNIQUEIDENTIFIER NOT NULL,
    NUMFEE DECIMAL(12,2) NOT NULL,
    NVCHSTATUS NVARCHAR(12) NOT NULL CONSTRAINT DF_ERSSSCHTBL_NVCHSTATUS DEFAULT (N'BOOKED'),
    DTMBOOKEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSSCHTBL_DTMBOOKEDAT DEFAULT SYSUTCDATETIME(),
    DTMCANCELAT DATETIME2(0) NULL,
    VCHCANCELBY NVARCHAR(50) NULL,
    VCHUPDATEBY NVARCHAR(50) NULL,
    DTMUPDATEDAT DATETIME2(0) NULL,
    VCHCREATEBY NVARCHAR(50) NOT NULL CONSTRAINT DF_ERSSSCHTBL_VCHCREATEBY DEFAULT (N'SYSTEM'),
    DTMCREATEDAT DATETIME2(0) NOT NULL CONSTRAINT DF_ERSSSCHTBL_DTMCREATEDAT DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_ERSSSCHTBL PRIMARY KEY (UIDSCHID),
    CONSTRAINT FK_ERSSSCHTBL_ERSSSLOTTBL FOREIGN KEY (UIDSLOTID) REFERENCES dbo.ERSSSLOTTBL (UIDSLOTID),
    CONSTRAINT FK_ERSSSCHTBL_ERSSUSERTBL FOREIGN KEY (UIDUSERID) REFERENCES dbo.ERSSUSERTBL (UIDUSERID),
    CONSTRAINT FK_ERSSSCHTBL_ERSSIDNTBL FOREIGN KEY (UIDIDNTYPE) REFERENCES dbo.ERSSIDNTBL (UIDIDNTYPE),
    CONSTRAINT CK_ERSSSCHTBL_NUMFEE CHECK (NUMFEE >= 0),
    CONSTRAINT CK_ERSSSCHTBL_STATUS CHECK (NVCHSTATUS IN (N'BOOKED', N'CANCELLED'))
);

-- 同一設定版本、同一身分別只允許一筆費率。
CREATE UNIQUE INDEX UQ_ERSSRESFEETBL_CFG_IDN
    ON dbo.ERSSRESFEETBL (UIDRESCFGID, UIDIDNTYPE);

-- 同一設備的未取消時段不可有完全相同的起訖。部分重疊由建立時段的流程檢查。
CREATE UNIQUE INDEX UQ_ERSSSLOTTBL_ACTIVE_RES_TIME
    ON dbo.ERSSSLOTTBL (UIDRESID, DTMSTARTAT, DTMENDAT)
    WHERE NVCHSTATUS <> N'CANCELLED';

-- 同一人同一時段只允許一筆有效預約。取消後仍可保留舊紀錄並重新預約。
CREATE UNIQUE INDEX UQ_ERSSSCHTBL_ACTIVE_SLOT_USER
    ON dbo.ERSSSCHTBL (UIDSLOTID, UIDUSERID)
    WHERE NVCHSTATUS = N'BOOKED';

-- 網站資料庫角色。建立應用程式使用者後，將其加入角色即可取得下列權限。
CREATE ROLE [erss_app_role];

-- 登入服務可讀取指定帳號欄位及更新最後登入時間。
GRANT SELECT ON OBJECT::dbo.ERSSACCTBL (UIDACCTID, NVCHUSERNAME, NVCHDISPLAYNAME, VCHPASSWORDHASH, NVCHLEVEL) TO [erss_app_role];
GRANT UPDATE ON OBJECT::dbo.ERSSACCTBL (DTMLASTLOGINAT) TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSUSERTBL TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSIDNTBL TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSRESTBL TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSRESCFGTBL TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSRESFEETBL TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSUSERRESTBL TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSSLOTTBL TO [erss_app_role];
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.ERSSSCHTBL TO [erss_app_role];

COMMIT TRANSACTION;
